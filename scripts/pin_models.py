"""Dev tool (needs the network): compute the pins for the model catalog and write src/parley/model_pins.py.

    uv run python scripts/pin_models.py                 # print the table, write nothing
    uv run python scripts/pin_models.py --write         # overwrite src/parley/model_pins.py
    uv run python scripts/pin_models.py --only llm-tiny stt-small.en
    uv run python scripts/pin_models.py --cross-check   # also download the smallest file of each repo and compare hashes

For Hugging Face repos it takes the latest commit, lists the files of THAT commit and uses the LFS `oid` (sha256) and
size from the API; small non-LFS files (config.json, ...) are downloaded and hashed. For the Kokoro files it reads the
GitHub release asset `digest`. It also prints the hosts the download redirects go to (compare with `models.HF_HOSTS`).
Review the diff of model_pins.py before committing: the file fixes what Parley will accept.
"""
import argparse
import hashlib
import re
import sys
from pathlib import Path
from urllib.parse import urlsplit

import httpx

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))
from parley import models  # noqa: E402

OUT = Path(__file__).resolve().parent.parent / "src" / "parley" / "model_pins.py"
HEX64 = re.compile(r"[0-9a-f]{64}")
SKIP = {".gitattributes", "README.md"}
RELEASE_API = "https://api.github.com/repos/thewh1teagle/kokoro-onnx/releases/tags/model-files-v1.0"
HEADER = '''"""Pinned file lists for the model catalog (`models.py`): per model id a revision and (file name, sha256, size) per file.

GENERATED by `uv run python scripts/pin_models.py --write` (needs the network); never typed by hand. A model that is
missing here is PENDING_PIN: it is listed in the catalog but the manager refuses to download it. A revision is a
40-hex Hugging Face commit (URLs use it instead of `main`) or, for the Kokoro files, the GitHub release tag.
"""

'''


def sha256_url(client: httpx.Client, url: str) -> tuple[str, int]:
    h, n = hashlib.sha256(), 0
    with client.stream("GET", url, follow_redirects=True) as r:
        r.raise_for_status()
        for chunk in r.iter_bytes(1 << 20):
            h.update(chunk)
            n += len(chunk)
    return h.hexdigest(), n


def redirect_host(client: httpx.Client, url: str) -> str:
    r = client.get(url, follow_redirects=False, headers={"Range": "bytes=0-0"})
    loc = r.headers.get("location")
    return urlsplit(loc).hostname or "?" if loc else f"(no redirect, status {r.status_code})"


def pin_hf(client: httpx.Client, spec: dict, cross_check: bool) -> dict:
    repo = spec["repo"]
    commit = client.get(f"https://huggingface.co/api/models/{repo}").raise_for_status().json()["sha"]
    if not re.fullmatch(r"[0-9a-f]{40}", commit):
        raise SystemExit(f"{repo}: unexpected commit {commit!r}")
    tree = client.get(f"https://huggingface.co/api/models/{repo}/tree/{commit}").raise_for_status().json()
    wanted = set(spec["probe"]) if spec["kind"] == "llm" else None
    files, smallest = [], None
    for e in sorted(tree, key=lambda e: e["path"]):
        name = e["path"]
        if e.get("type") != "file" or "/" in name or name in SKIP or (wanted is not None and name not in wanted):
            continue
        url = f"https://huggingface.co/{repo}/resolve/{commit}/{name}"
        lfs = e.get("lfs")
        if lfs and HEX64.fullmatch(lfs.get("oid", "")):
            sha, size = lfs["oid"], int(lfs["size"])
            print(f"  {name}: LFS, redirects to {redirect_host(client, url)}")
            if smallest is None or size < smallest[2]:
                smallest = (name, url, size, sha)
        else:
            sha, size = sha256_url(client, url)
        files.append((name, sha, size))
    if wanted is not None and {f[0] for f in files} != wanted:
        raise SystemExit(f"{repo}: expected {sorted(wanted)}, found {[f[0] for f in files]}")
    if not files:
        raise SystemExit(f"{repo}: no files found")
    if cross_check and smallest:
        got, n = sha256_url(client, smallest[1])
        if (got, n) != (smallest[3], smallest[2]):
            raise SystemExit(f"{repo}/{smallest[0]}: downloaded hash differs from the API value")
        print(f"  cross-check ok: {smallest[0]}")
    return {"revision": commit, "files": files}


def pin_kokoro(client: httpx.Client, specs: list[dict]) -> dict[str, dict]:
    assets = {a["name"]: a for a in client.get(RELEASE_API).raise_for_status().json()["assets"]}
    out = {}
    for spec in specs:
        files = []
        for name in spec["probe"]:
            a = assets.get(name)
            if a is None:
                raise SystemExit(f"release has no asset {name}")
            digest = str(a.get("digest") or "")
            if digest.startswith("sha256:") and HEX64.fullmatch(digest[7:]):
                files.append((name, digest[7:], int(a["size"])))
            else:  # older releases carry no digest: hash a real download
                sha, size = sha256_url(client, models.KOKORO_URL + name)
                files.append((name, sha, size))
        out[spec["id"]] = {"revision": "model-files-v1.0", "files": files}
    return out


def render(pins: dict[str, dict]) -> str:
    lines = ["PINS: dict[str, dict] = {"]
    for mid in sorted(pins):
        p = pins[mid]
        lines.append(f'    "{mid}": {{"revision": "{p["revision"]}", "files": [')
        for name, sha, size in p["files"]:
            lines.append(f'        ("{name}", "{sha}", {size}),')
        lines.append("    ]},")
    lines.append("}")
    return HEADER + "\n".join(lines) + "\n"


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write", action="store_true", help="overwrite src/parley/model_pins.py")
    ap.add_argument("--only", nargs="*", help="catalog ids to (re)compute; others keep their current pins")
    ap.add_argument("--cross-check", action="store_true", help="download the smallest LFS file per repo and compare")
    args = ap.parse_args()
    specs = [s for s in models.SPECS if not args.only or s["id"] in args.only]
    pins = {} if args.only is None else dict(models.PINS)
    with httpx.Client(timeout=httpx.Timeout(30, read=300)) as client:
        for spec in (s for s in specs if s["kind"] != "tts"):
            print(spec["id"])
            pins[spec["id"]] = pin_hf(client, spec, args.cross_check)
        tts = [s for s in specs if s["kind"] == "tts"]
        if tts:
            print("kokoro")
            pins.update(pin_kokoro(client, tts))
    text = render(pins)
    if args.write:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT}")
    else:
        print(text)


if __name__ == "__main__":
    main()
